// Unit 1 (see TruthTableWorkspace.jsx): truth tables, as the course opens.
// The connectives are defined by their truth tables, and two statements are
// logically equivalent when their columns are the same, in every assignment
// of truth values to the atomic statements. The levels follow the slides of
// the first lecture, and the equivalences proved here are the laws that the
// move "לפי השקילות" offers later (unit 6). The equivalences of quantifiers
// cannot be checked in a table: they are proved by moves, in units 5 and 6.
// Each level gives the statements to compute; the table has a column for each
// of their parts, inner ones first, and the student fills in T or F.

